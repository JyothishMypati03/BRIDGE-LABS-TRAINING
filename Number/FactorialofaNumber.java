package LAB.Number;

import java.util.*;


public class FactorialofaNumber {

	public static void main(String[] args) {
		
		Scanner scan = new Scanner(System.in);
		
		int n = scan.nextInt();
		
		
		if(n==0 || n==1) {
			
			System.out.print(1);
			return;
			
		}
		
		System.out.print(n*(n-1));
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		

	}

}
